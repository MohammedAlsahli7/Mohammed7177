// Rebuilds _ds_bundle.js from components/** — no design tool needed.
// A component = PascalCase X.jsx/.tsx with a sibling X.d.ts. Every named
// export lands on window.InfillDesignSystem_d33a9b (read by the site as `B` /
// `S`). React/ReactDOM come from the page's globals.
// .css imports inside components are injected as <style> tags.
// Usage: node scripts/build-ds.cjs [outFile]   (default: ./_ds_bundle.js)
const {build} = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const NAMESPACE = 'InfillDesignSystem_d33a9b';

/**
 * Finds every component: a PascalCase X.d.ts with a sibling X.jsx / X.tsx.
 * @param {string} dir
 * @param {!Array<string>=} out
 * @return {!Array<string>} Source files.
 */
function findComponents(dir, out = []) {
  for (const e of fs.readdirSync(dir, {withFileTypes: true})) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      findComponents(p, out);
      continue;
    }
    const m = e.name.match(/^([A-Z][A-Za-z0-9]*)\.d\.ts$/);
    if (!m) continue;
    const src = ['.jsx', '.tsx']
      .map((x) => path.join(dir, m[1] + x))
      .find((f) => fs.existsSync(f));
    if (src) out.push(src);
  }
  return out;
}

const globals = {
  name: 'globals',
  setup(b) {
    b.onResolve({filter: /^react(-dom)?(\/.*)?$/}, (a) => ({
      path: a.path,
      namespace: 'global',
    }));
    b.onLoad({filter: /.*/, namespace: 'global'}, (a) => ({
      contents:
        'module.exports = window.' +
        (a.path.startsWith('react-dom') ? 'ReactDOM' : 'React') +
        ';',
      loader: 'js',
    }));
    b.onLoad({filter: /\.css$/}, (a) => ({
      contents:
        'const s=document.createElement("style");s.setAttribute("data-ds",' +
        JSON.stringify(path.relative(ROOT, a.path)) +
        ');s.textContent=' +
        JSON.stringify(fs.readFileSync(a.path, 'utf8')) +
        ';document.head.appendChild(s);',
      loader: 'js',
    }));
  },
};

/**
 * Bundles components/** into one IIFE on window.InfillDesignSystem_d33a9b.
 * @param {string=} outFile
 * @return {!Promise<number>} How many components went in.
 */
async function buildDs(outFile = path.join(ROOT, '_ds_bundle.js')) {
  const files = findComponents(path.join(ROOT, 'components')).sort();
  if (!files.length) {
    throw new Error(
      'No components found (need X.jsx + X.d.ts pairs under components/).',
    );
  }
  const entry = files
    .map(
      (f) =>
        'export * from ' +
        JSON.stringify(
          './' + path.relative(ROOT, f).split(path.sep).join('/'),
        ) +
        ';',
    )
    .join('\n');
  await build({
    stdin: {
      contents: entry,
      resolveDir: ROOT,
      sourcefile: 'ds-entry.js',
      loader: 'js',
    },
    bundle: true,
    format: 'iife',
    globalName: '__ds_build',
    target: 'es2019',
    jsx: 'transform',
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    loader: {'.jsx': 'jsx', '.tsx': 'tsx'},
    plugins: [globals],
    footer: {
      js: `(window.${NAMESPACE} = window.${NAMESPACE} || {}); Object.assign(window.${NAMESPACE}, __ds_build);`,
    },
    banner: {
      js: `/* ${NAMESPACE} — generated by scripts/build-ds.cjs from components/**. Do not edit by hand. */`,
    },
    outfile: outFile,
    minify: process.env.NODE_ENV === 'production',
    legalComments: 'none',
    logLevel: 'warning',
  });
  return files.length;
}

module.exports = {buildDs};
if (require.main === module) {
  buildDs(process.argv[2] && path.resolve(process.argv[2]))
    .then((n) =>
      console.log('✓ _ds_bundle.js rebuilt from ' + n + ' components'),
    )
    .catch((e) => {
      console.error(e.message || e);
      process.exit(1);
    });
}
